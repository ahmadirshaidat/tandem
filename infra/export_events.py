"""Export the backend's event names and JSON schema; --check detects contract drift."""

import argparse
import json
import sys
from pathlib import Path
from typing import get_args

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "backend"))
from app.channels.schemas import EventType, SocketCommand, SocketEvent

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
names = get_args(EventType)
outputs = {
    root
    / "frontend/src/lib/events.generated.ts": "// Generated by infra/export_events.py; do not edit.\nexport const eventTypes = "
    + json.dumps(names)
    + " as const;\nexport type EventType = (typeof eventTypes)[number];\n",
    root / "docs/channel-events.schema.json": json.dumps(
        {
            "event": SocketEvent.model_json_schema(),
            "command": SocketCommand.model_json_schema(),
        },
        indent=2,
    )
    + "\n",
}
for path, contents in outputs.items():
    if args.check:
        if path.read_text() != contents:
            raise SystemExit(f"Event contract out of date: {path.relative_to(root)}")
    else:
        path.write_text(contents)
