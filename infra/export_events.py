"""Export the backend's event names and JSON schema; --check detects contract drift."""

import argparse
import json
import sys
from pathlib import Path
from typing import get_args

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "backend"))
from app.channels.schemas import EventType, SocketCommand, SocketEvent  # noqa: E402

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
names = get_args(EventType)


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if not schema.get("properties"):
            additional = schema.get("additionalProperties")
            return "Record<string, " + (ts_type(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = schema.get("required", [])
        return (
            "{\n"
            + "".join(
                f"  {key}{'' if key in required else '?'}: {ts_type(value)};\n"
                for key, value in schema.get("properties", {}).items()
            )
            + "}"
        )
    if kind == "array":
        return "Array<" + ts_type(schema["items"]) + ">"
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "null": "null",
        "boolean": "boolean",
    }.get(kind, "unknown")


schema = SocketEvent.model_json_schema()
contract = "// Generated by infra/export_events.py; do not edit.\n"
contract += (
    "export const eventTypes = [\n"
    + "".join("  " + json.dumps(name) + ",\n" for name in names)
    + "] as const;\nexport type EventType = (typeof eventTypes)[number];\n"
)
for name, definition in schema.get("$defs", {}).items():
    contract += f"export type {name} = {ts_type(definition)};\n"
contract += f"export type SocketEvent = {ts_type(schema)};\n"
outputs = {
    root / "frontend/src/lib/events.generated.ts": contract,
    root / "docs/channel-events.schema.json": json.dumps(
        {"event": schema, "command": SocketCommand.model_json_schema()}, indent=2
    )
    + "\n",
}

for path, contents in outputs.items():
    if args.check:
        if path.read_text() != contents:
            raise SystemExit(f"Event contract out of date: {path.relative_to(root)}")
    else:
        path.write_text(contents)
